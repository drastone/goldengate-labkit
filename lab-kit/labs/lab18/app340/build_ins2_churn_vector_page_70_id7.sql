create or replace view soe.ins2_churn_seed_match_v as
select log_id,
       seed_code,
       churn_reason,
       recommended_action,
       vector_distance
  from (
    select c.log_id,
           s.seed_code,
           s.churn_reason,
           s.recommended_action,
           vector_distance(c.consult_vector, s.seed_vector) vector_distance,
           row_number() over (
             partition by c.log_id
             order by vector_distance(c.consult_vector, s.seed_vector), s.seed_weight desc
           ) rn
      from soe.ins2_churn_call_vector c
      join soe.ins2_churn_seed_phrase s
        on c.consult_vector is not null
       and s.seed_vector is not null
  )
 where rn = 1;

create or replace view soe.ins2_churn_log_score_v as
select c.log_id,
       c.source_cust_id,
       c.event_time,
       c.work_dt,
       c.fund_code,
       c.fund_name,
       c.call_cnt_3m,
       c.late_pmt_cnt,
       c.consult_text,
       c.vector_status,
       m.seed_code,
       coalesce(m.churn_reason, soe.ins2_churn_vector_pkg.keyword_reason(c.consult_text)) churn_reason,
       m.vector_distance,
       case
         when m.vector_distance is not null then round(100 / (1 + m.vector_distance), 1)
       end vector_similarity_score,
       soe.ins2_churn_vector_pkg.keyword_score(c.consult_text, c.call_cnt_3m, c.late_pmt_cnt) keyword_score,
       least(
         100,
         round(
           greatest(
             soe.ins2_churn_vector_pkg.keyword_score(c.consult_text, c.call_cnt_3m, c.late_pmt_cnt),
             nvl(100 / (1 + m.vector_distance), 0) * 0.75
             + soe.ins2_churn_vector_pkg.keyword_score(c.consult_text, c.call_cnt_3m, c.late_pmt_cnt) * 0.25
           ),
           1
         )
       ) churn_score,
       soe.ins2_churn_vector_pkg.risk_band(
         least(
           100,
           round(
             greatest(
               soe.ins2_churn_vector_pkg.keyword_score(c.consult_text, c.call_cnt_3m, c.late_pmt_cnt),
               nvl(100 / (1 + m.vector_distance), 0) * 0.75
               + soe.ins2_churn_vector_pkg.keyword_score(c.consult_text, c.call_cnt_3m, c.late_pmt_cnt) * 0.25
             ),
             1
           )
         )
       ) risk_band,
       coalesce(m.recommended_action,
                soe.ins2_churn_vector_pkg.suggested_action(
                  soe.ins2_churn_vector_pkg.keyword_reason(c.consult_text)
                )) suggested_care_action,
       1 + mod(c.source_cust_id, 10) suggested_fp_id
  from soe.ins2_churn_call_vector c
  left join soe.ins2_churn_seed_match_v m
    on m.log_id = c.log_id;

create or replace view soe.ins2_churn_candidate_v as
select log_id,
       source_cust_id,
       event_time,
       fund_code,
       fund_name,
       call_cnt_3m,
       late_pmt_cnt,
       consult_text,
       vector_status,
       seed_code,
       churn_reason,
       vector_distance,
       vector_similarity_score,
       keyword_score,
       churn_score,
       risk_band,
       suggested_care_action,
       suggested_fp_id
  from (
    select s.*,
           row_number() over (
             partition by source_cust_id
             order by churn_score desc, event_time desc nulls last, log_id desc
           ) rn
      from soe.ins2_churn_log_score_v s
  )
 where rn = 1;

create or replace view soe.ins2_churn_action_queue_v as
with latest_care as (
  select care_id,
         source_cust_id,
         log_id,
         assigned_fp_id,
         care_status,
         due_date,
         campaign_name,
         action_memo,
         row_number() over (
           partition by source_cust_id
           order by nvl(updated_at, created_at) desc, care_id desc
         ) rn
    from soe.ins2_churn_fp_care
)
select c.source_cust_id,
       c.log_id,
       c.event_time,
       c.fund_name,
       c.churn_score,
       c.risk_band,
       c.churn_reason,
       c.vector_distance,
       c.keyword_score,
       c.call_cnt_3m,
       c.late_pmt_cnt,
       c.consult_text,
       coalesce(l.assigned_fp_id, c.suggested_fp_id) assigned_fp_id,
       coalesce(l.care_status, '대상선정') care_status,
       coalesce(l.due_date, trunc(sysdate) + case when c.churn_score >= 85 then 1 when c.churn_score >= 70 then 3 else 7 end) due_date,
       coalesce(l.campaign_name, '해약 방어 케어') campaign_name,
       coalesce(l.action_memo, c.suggested_care_action) action_memo
  from soe.ins2_churn_candidate_v c
  left join latest_care l
    on l.source_cust_id = c.source_cust_id
   and l.rn = 1
 where c.churn_score >= 55;

create or replace view soe.ins2_churn_kpi_v as
select '케어 대상' label,
       to_char(count(*)) value,
       'fa-user-md' icon,
       'u-color-2' color
  from soe.ins2_churn_action_queue_v
union all
select '긴급케어',
       to_char(sum(case when risk_band = '긴급케어' then 1 else 0 end)),
       'fa-phone',
       'u-color-1'
  from soe.ins2_churn_action_queue_v
union all
select '평균 위험점수',
       to_char(round(avg(churn_score), 1), 'FM990.0'),
       'fa-line-chart',
       'u-color-4'
  from soe.ins2_churn_action_queue_v
union all
select '벡터 산출 로그',
       to_char(sum(case when vector_status = 'READY' then 1 else 0 end)),
       'fa-cube',
       'u-color-21'
  from soe.ins2_churn_candidate_v;

create or replace function soe.ins2_churn_kpi_html return clob authid definer is
  l_html clob := '<div class="churn-kpi-grid" style="display:grid;grid-template-columns:repeat(4,minmax(150px,1fr));gap:12px">';
