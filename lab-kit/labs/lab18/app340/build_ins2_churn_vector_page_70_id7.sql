create or replace package body soe.ins2_churn_vector_pkg as
  function has_text(p_text varchar2, p_pattern varchar2) return boolean deterministic is
  begin
    return instr(lower(nvl(p_text, '')), lower(p_pattern)) > 0;
  end;

  function keyword_reason(p_text varchar2) return varchar2 deterministic is
  begin
    if has_text(p_text, '환급금') or has_text(p_text, '수익률') or has_text(p_text, '보험료') then
      return '보험료·수익률 불만';
    elsif has_text(p_text, '타사') or has_text(p_text, '갈아타') or has_text(p_text, '이전') then
      return '타사 이동 검토';
    elsif has_text(p_text, '경기 악화') or has_text(p_text, '유지 어렵') or has_text(p_text, '부담') then
      return '경제적 어려움';
    elsif has_text(p_text, '콜센터') or has_text(p_text, '상담') or has_text(p_text, '불친절') then
      return '상담·서비스 불만';
    elsif has_text(p_text, '청구') or has_text(p_text, '보험금') or has_text(p_text, '지급') then
      return '보험금 청구 불만';
    elsif has_text(p_text, '앱') or has_text(p_text, '인증') or has_text(p_text, '모바일') then
      return '디지털 이용 불편';
    else
      return '일반 문의';
    end if;
  end;

  function keyword_score(
    p_text varchar2,
    p_call_cnt_3m number,
    p_late_pmt_cnt number
  ) return number deterministic is
    l_score number := 0;
  begin
    if has_text(p_text, '해약') or has_text(p_text, '해지') or has_text(p_text, '중도 해지') then
      l_score := l_score + 45;
    end if;
    if has_text(p_text, '환급금') or has_text(p_text, '불이익') or has_text(p_text, '갈아타') then
      l_score := l_score + 20;
    end if;
    if has_text(p_text, '유지 어렵') or has_text(p_text, '보험료') or has_text(p_text, '경기 악화') then
      l_score := l_score + 15;
    end if;
    if has_text(p_text, '불만') or has_text(p_text, '불친절') or has_text(p_text, '지연') then
      l_score := l_score + 10;
    end if;

    l_score := l_score + least(nvl(p_call_cnt_3m, 0) * 2, 20);
    l_score := l_score + least(nvl(p_late_pmt_cnt, 0) * 6, 18);

    return least(100, round(l_score, 1));
  end;

  function suggested_action(p_reason varchar2) return varchar2 deterministic is
  begin
    return case p_reason
      when '보험료·수익률 불만' then '환급 손실·보장 공백 설명 후 감액완납/납입유예 상담'
      when '타사 이동 검토' then '기존 계약 예정이율·면책기간·보장 차이 비교 리포트 제공'
      when '경제적 어려움' then '납입 일시중지, 보험료 조정, 자동이체 실패 원인 점검'
      when '상담·서비스 불만' then 'FP 해피콜, 사과 및 전담 처리 약속'
      when '보험금 청구 불만' then '청구 지급 사유 재검토 및 추가 담보/서류 안내'
      when '디지털 이용 불편' then '방문 또는 원격 지원으로 앱/인증/청구 절차 안내'
      else '최근 상담 이력 확인 후 유지 가치 리마인드 캠페인'
    end;
  end;

  function risk_band(p_score number) return varchar2 deterministic is
  begin
    if nvl(p_score, 0) >= 85 then
      return '긴급케어';
    elsif nvl(p_score, 0) >= 70 then
      return '고위험';
    elsif nvl(p_score, 0) >= 55 then
      return '관찰';
    else
      return '일반';
    end if;
  end;

  procedure refresh_vectors(p_max_logs number default 5000) is
    l_err varchar2(1000);
  begin
    execute immediate q'[
      merge into soe.ins2_churn_call_vector d
      using (
        select log_id,
               cust_id source_cust_id,
               case
                 when regexp_like(work_dt_ts, '^[0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2}:[0-9]{2}$')
                 then to_timestamp(work_dt_ts, 'YYYY-MM-DD HH24:MI:SS')
               end event_time,
               work_dt,
               fund_code,
               fund_name,
               call_cnt_3m,
               late_pmt_cnt,
               consult_text
          from (
            select log_id, cust_id, work_dt, work_dt_ts, fund_code, fund_name,
                   call_cnt_3m, late_pmt_cnt, consult_text
              from soe.call_center_log
             where consult_text is not null
             order by log_id desc
          )
         where rownum <= nvl(:max_logs, 1000000000)
      ) s
      on (d.log_id = s.log_id)
      when matched then update set
        d.source_cust_id = s.source_cust_id,
        d.event_time = s.event_time,
        d.work_dt = s.work_dt,
        d.fund_code = s.fund_code,
        d.fund_name = s.fund_name,
        d.call_cnt_3m = s.call_cnt_3m,
        d.late_pmt_cnt = s.late_pmt_cnt,
        d.consult_text = s.consult_text,
        d.refreshed_at = systimestamp
      when not matched then insert
        (log_id, source_cust_id, event_time, work_dt, fund_code, fund_name,
         call_cnt_3m, late_pmt_cnt, consult_text, vector_status, refreshed_at)
      values
        (s.log_id, s.source_cust_id, s.event_time, s.work_dt, s.fund_code, s.fund_name,
         s.call_cnt_3m, s.late_pmt_cnt, s.consult_text, 'PENDING', systimestamp)
    ]' using p_max_logs;

    for r in (
      select seed_code, seed_text
        from soe.ins2_churn_seed_phrase
       where seed_vector is null or vector_status <> 'READY'
    ) loop
      begin
        update soe.ins2_churn_seed_phrase
           set seed_vector = dbms_vector.utl_to_embedding(
                                r.seed_text,
                                json('{"model":"GGADMIN.CHURN_MODEL"}')
                              ),
               vector_status = 'READY',
               vector_error = null,
               updated_at = systimestamp
         where seed_code = r.seed_code;
      exception
        when others then
          l_err := substr(sqlerrm, 1, 1000);
          update soe.ins2_churn_seed_phrase
             set vector_status = 'FALLBACK',
                 vector_error = l_err,
                 updated_at = systimestamp
           where seed_code = r.seed_code;
      end;
    end loop;

    for r in (
      select log_id, consult_text
        from (
          select log_id, consult_text
            from soe.ins2_churn_call_vector
           where consult_text is not null
             and (consult_vector is null or vector_status <> 'READY')
           order by log_id desc
        )
       where rownum <= nvl(p_max_logs, 1000000000)
    ) loop
      begin
        update soe.ins2_churn_call_vector
           set consult_vector = dbms_vector.utl_to_embedding(
                                  r.consult_text,
                                  json('{"model":"GGADMIN.CHURN_MODEL"}')
                                ),
               vector_status = 'READY',
               vector_error = null,
               refreshed_at = systimestamp
         where log_id = r.log_id;
      exception
        when others then
          l_err := substr(sqlerrm, 1, 1000);
          update soe.ins2_churn_call_vector
             set vector_status = 'FALLBACK',
                 vector_error = l_err,
                 refreshed_at = systimestamp
           where log_id = r.log_id;
      end;
    end loop;

    commit;
  exception
    when others then
      dbms_output.put_line('refresh_vectors skipped: ' || sqlerrm);
      commit;
  end;

  procedure sync_care_queue is
  begin
    execute immediate q'[
      merge into soe.ins2_churn_fp_care d
      using (
        select source_cust_id,
               log_id,
               suggested_fp_id assigned_fp_id,
               churn_score,
               risk_band,
               churn_reason,
               suggested_care_action
          from soe.ins2_churn_candidate_v
         where churn_score >= 55
      ) s
      on (
        d.source_cust_id = s.source_cust_id
        and d.care_status in ('대상선정', 'FP배정', '캠페인대상')
      )
      when matched then update set
        d.log_id = s.log_id,
        d.assigned_fp_id = s.assigned_fp_id,
        d.churn_score = s.churn_score,
        d.risk_band = s.risk_band,
        d.churn_reason = s.churn_reason,
        d.action_memo = s.suggested_care_action,
        d.due_date = trunc(sysdate) + case when s.churn_score >= 85 then 1 when s.churn_score >= 70 then 3 else 7 end,
        d.updated_at = systimestamp
      when not matched then insert
        (source_cust_id, log_id, assigned_fp_id, churn_score, risk_band,
         churn_reason, care_status, due_date, campaign_name, action_memo)
      values
        (s.source_cust_id, s.log_id, s.assigned_fp_id, s.churn_score, s.risk_band,
         s.churn_reason, '대상선정',
         trunc(sysdate) + case when s.churn_score >= 85 then 1 when s.churn_score >= 70 then 3 else 7 end,
         '해약 방어 케어',
         s.suggested_care_action)
    ]';

    commit;
  end;
end;
