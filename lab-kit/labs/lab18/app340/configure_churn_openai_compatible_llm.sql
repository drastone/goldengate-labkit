         '&base_url' base_url,
         '&model_name' model_name,
         '&api_key' api_key
    from dual
) s
on (d.config_name = s.config_name)
when matched then update set
  d.provider = s.provider,
  d.base_url = s.base_url,
  d.model_name = s.model_name,
  d.api_key = s.api_key,
  d.enabled = 'Y',
  d.updated_at = systimestamp
when not matched then insert
  (config_name, provider, base_url, model_name, api_key, enabled, updated_at)
values
  (s.config_name, s.provider, s.base_url, s.model_name, s.api_key, 'Y', systimestamp);

create or replace package soe.ins2_churn_llm_pkg authid definer as
  function smoke_test return clob;
  procedure generate_comments(p_limit number default 2);
end ins2_churn_llm_pkg;
