create or replace package body soe.ins2_churn_llm_pkg as
  procedure load_config(
    p_provider   out varchar2,
    p_base_url   out varchar2,
    p_model_name out varchar2,
    p_api_key    out varchar2
  ) is
  begin
    select provider, base_url, model_name, api_key
      into p_provider, p_base_url, p_model_name, p_api_key
      from soe.ins2_churn_llm_config
     where config_name = 'DEFAULT'
       and enabled = 'Y';
  exception
    when no_data_found then
      raise_application_error(-20001, 'LLM provider config DEFAULT is not enabled.');
  end load_config;

  function request_llm(p_prompt clob) return clob is
    l_provider   varchar2(40);
    l_base_url   varchar2(1000);
    l_model_name varchar2(200);
    l_api_key    varchar2(4000);
    l_body       clob;
    l_body_text  varchar2(32767);
    l_body_raw   raw(32767);
    l_response   clob;
    l_comment    varchar2(4000);
    l_req        utl_http.req;
    l_resp       utl_http.resp;
    l_chunk      varchar2(32767);
  begin
    load_config(l_provider, l_base_url, l_model_name, l_api_key);

    select json_object(
             'model' value l_model_name,
             'messages' value json_array(
               json_object(
                 'role' value 'system',
                 'content' value '당신은 보험사 담당 FP를 돕는 고객 이탈 방지 코치입니다. 고객에게 직접 보내는 문자가 아니라 FP 내부 참고용 대응 코멘트를 한국어로 간결하게 작성하십시오.'
               ),
               json_object(
                 'role' value 'user',
                 'content' value p_prompt
               )
             ),
             'temperature' value 0.3,
             'max_tokens' value 300
             returning clob
           )
      into l_body
      from dual;

    l_response := empty_clob();
    dbms_lob.createtemporary(l_response, true);
    l_body_text := dbms_lob.substr(l_body, 32767, 1);
    l_body_raw := utl_i18n.string_to_raw(l_body_text, 'AL32UTF8');

    l_req := utl_http.begin_request(l_base_url, 'POST', 'HTTP/1.1');
    utl_http.set_body_charset(l_req, 'UTF-8');
    utl_http.set_header(l_req, 'Content-Type', 'application/json; charset=utf-8');
    utl_http.set_header(l_req, 'Authorization', 'Bearer ' || l_api_key);
    utl_http.set_header(l_req, 'Content-Length', utl_raw.length(l_body_raw));
    utl_http.write_raw(l_req, l_body_raw);

    l_resp := utl_http.get_response(l_req);

    begin
      loop
        utl_http.read_text(l_resp, l_chunk, 32767);
        dbms_lob.writeappend(l_response, length(l_chunk), l_chunk);
      end loop;
    exception
      when utl_http.end_of_body then
        utl_http.end_response(l_resp);
    end;

    l_comment := json_value(l_response, '$.choices[0].message.content' returning varchar2(4000));

    if l_comment is null then
      raise_application_error(-20002, 'LLM response did not contain choices[0].message.content: ' || dbms_lob.substr(l_response, 500, 1));
    end if;

    return l_comment;
  end request_llm;

  function smoke_test return clob is
  begin
    return request_llm('한국어 한 문장으로 답하십시오. GoldenGate CDC 이벤트를 FP 고객 케어 메시지로 연결합니다.');
  end smoke_test;

  procedure generate_comments(p_limit number default 2) is
    l_provider   varchar2(40);
    l_base_url   varchar2(1000);
    l_model_name varchar2(200);
    l_api_key    varchar2(4000);
    l_prompt     clob;
    l_comment    clob;
    l_error      varchar2(1000);
  begin
    load_config(l_provider, l_base_url, l_model_name, l_api_key);

    for r in (
      select *
        from (
          select source_cust_id,
                 log_id,
                 customer_name,
                 assigned_fp_id,
                 work_type,
                 contact_priority,
                 risk_band,
                 churn_score,
                 churn_reason,
                 fund_name,
                 call_cnt_3m,
                 late_pmt_cnt,
                 consult_text,
                 action_memo,
                 fp_coach_comment
            from soe.ins2_churn_action_queue_v q
           where not exists (
                   select 1
                     from soe.ins2_churn_llm_result x
                    where x.source_cust_id = q.source_cust_id
                      and nvl(x.log_id, -1) = nvl(q.log_id, -1)
                      and x.status = 'GENERATED'
                 )
           order by contact_rank, churn_score desc, source_cust_id
        )
       where rownum <= p_limit
    ) loop
      begin
        l_prompt :=
          '업무유형: ' || nvl(r.work_type, '-') || chr(10) ||
          '접촉우선순위: ' || nvl(r.contact_priority, '-') || chr(10) ||
          '고객명: ' || nvl(r.customer_name, '고객ID ' || r.source_cust_id) || chr(10) ||
          '담당 FP: ' || nvl(to_char(r.assigned_fp_id), '-') || chr(10) ||
          '위험등급/점수: ' || nvl(r.risk_band, '-') || ' / ' || nvl(to_char(round(r.churn_score, 1)), '-') || chr(10) ||
          '주요사유: ' || nvl(r.churn_reason, '-') || chr(10) ||
          '상품: ' || nvl(r.fund_name, '-') || chr(10) ||
          '최근 3개월 상담 횟수: ' || nvl(to_char(r.call_cnt_3m), '-') || chr(10) ||
          '연체 횟수: ' || nvl(to_char(r.late_pmt_cnt), '-') || chr(10) ||
          '최근 상담 내용: ' || nvl(r.consult_text, '-') || chr(10) ||
          '권장 액션: ' || nvl(r.action_memo, '-') || chr(10) ||
          '위 내용을 바탕으로 담당 FP가 고객에게 연락하기 전에 참고할 대응 코멘트를 3문장 이내로 작성하십시오. 공감, 확인 질문, 유지 대안을 포함하십시오.';

        l_comment := request_llm(l_prompt);

        merge into soe.ins2_churn_llm_result d
        using (
          select r.source_cust_id source_cust_id,
                 r.log_id log_id
            from dual
        ) s
        on (d.source_cust_id = s.source_cust_id and nvl(d.log_id, -1) = nvl(s.log_id, -1))
        when matched then update set
          d.provider = l_provider,
          d.model_name = l_model_name,
          d.prompt_text = l_prompt,
          d.llm_comment = l_comment,
          d.status = 'GENERATED',
          d.error_message = null,
          d.generated_at = systimestamp,
          d.updated_at = systimestamp
        when not matched then insert
          (source_cust_id, log_id, provider, model_name, prompt_text, llm_comment, status, error_message, generated_at, updated_at)
        values
          (r.source_cust_id, r.log_id, l_provider, l_model_name, l_prompt, l_comment, 'GENERATED', null, systimestamp, systimestamp);
      exception
        when others then
          l_error := substr(sqlerrm, 1, 1000);

          merge into soe.ins2_churn_llm_result d
          using (
            select r.source_cust_id source_cust_id,
                   r.log_id log_id
              from dual
          ) s
          on (d.source_cust_id = s.source_cust_id and nvl(d.log_id, -1) = nvl(s.log_id, -1))
          when matched then update set
            d.provider = l_provider,
            d.model_name = l_model_name,
            d.prompt_text = l_prompt,
            d.status = 'ERROR',
            d.error_message = l_error,
            d.updated_at = systimestamp
          when not matched then insert
            (source_cust_id, log_id, provider, model_name, prompt_text, status, error_message, updated_at)
          values
            (r.source_cust_id, r.log_id, l_provider, l_model_name, l_prompt, 'ERROR', l_error, systimestamp);
      end;
    end loop;

    commit;
  end generate_comments;
end ins2_churn_llm_pkg;
/

